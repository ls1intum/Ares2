				public static boolean isGuarding(String test) {
					return test.equals(GUARDING.get());
				}

				/** Tells another generated hook whether this context is hidden. */
				public static boolean isHiddenContext(ExtensionContext context) {
					Optional<Class<?>> testClass = nearest(context, ExtensionContext::getTestClass);
					Optional<String> methodName = nearest(context, ExtensionContext::getTestMethod).map(Method::getName);
					return testClass.isPresent() && (isHidden(testClass.get(), methodName)
							|| methodName.isEmpty() && containsHiddenMethod(testClass.get()));
				}

